// Regenerates offline/data.js from src/components/system/steps.ts.
// Committed output means the APK workflow needs no extra toolchain: it just
// copies the already-generated static files into the Android assets.
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { writeFileSync } from "node:fs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const json = execFileSync(
  process.execPath,
  ["--experimental-strip-types", join(root, "scripts/export-steps.mjs")],
  { cwd: root, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 },
);
JSON.parse(json); // fail loudly if the exporter produced something else
const out = [
  "// Generated by scripts/build-offline-data.mjs — do not edit by hand.",
  "// Source of truth: src/components/system/steps.ts",
  `window.STUDY_DATA = ${json};`,
  "",
].join("\n");
writeFileSync(join(root, "offline/data.js"), out);
console.log(`wrote offline/data.js (${json.length} bytes of study data)`);
